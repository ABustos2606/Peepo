"""Write config/catalogue/inventory.txt, the plugins the catalogue may offer.

The selected inventory (P9.1) is every plugin identity in Beebo's module map
and in Poly's public plugin sources, as recorded in
docs/lv2-plugin-comparison-data.json, plus the MDA effects and LV2 examples
the development engine uses as conventional effects and test plugins,
Peepo's own plugins, and the complete pinned GxPlugins collection. The
exporter offers only what this list names (`--only`): installing a package
does not put its other plugins in front of the player.
    python3 tools/catalogue-inventory.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "docs", "lv2-plugin-comparison-data.json")
GX = os.path.join(ROOT, "config", "catalogue", "gxplugins.json")
PATCHSTORAGE = os.path.join(ROOT, "config", "catalogue", "patchstorage.json")
RETIRED = os.path.join(ROOT, "config", "catalogue", "retired.json")
OUT = os.path.join(ROOT, "config", "catalogue", "inventory.txt")

MDA = ["Ambience", "Bandisto", "BeatBox", "Combo", "DX10", "DeEss", "Degrade", "Delay", "Detune", "Dither", "DubDelay",
       "Dynamics", "EPiano", "Image", "JX10", "Leslie", "Limiter", "Loudness", "MultiBand", "Overdrive", "Piano", "RePsycho",
       "RezFilter", "RingMod", "RoundPan", "Shepard", "Splitter", "Stereo", "SubSynth", "TalkBox", "TestTone", "ThruZero",
       "Tracker", "Transient", "VocInput", "Vocoder"]
# Peepo's own plugins: plugins/ of this repository, and Discipline, Loo-pi, Chamber and Drizzle from their own.
PEEPO = ["urn:peepo:lv2:footswitch",
         "https://github.com/ABustos2606/discipline#discipline", "https://github.com/ABustos2606/discipline#return",
         "https://github.com/ABustos2606/loo-pi#loopi",
         "https://github.com/ABustos2606/chamber#chamber",
         "https://github.com/ABustos2606/drizzle#drizzle", "https://github.com/ABustos2606/drizzle#synth",
         "https://github.com/ABustos2606/aura#aura"]
# Eureka: twelve independent effects (M7).
PEEPO += ['https://github.com/ABustos2606/eureka#slowmo', 'https://github.com/ABustos2606/eureka#hush', 'https://github.com/ABustos2606/eureka#bloom', 'https://github.com/ABustos2606/eureka#skip', 'https://github.com/ABustos2606/eureka#ripple', 'https://github.com/ABustos2606/eureka#prism', 'https://github.com/ABustos2606/eureka#spool', 'https://github.com/ABustos2606/eureka#granny', 'https://github.com/ABustos2606/eureka#spark', 'https://github.com/ABustos2606/eureka#chime', 'https://github.com/ABustos2606/eureka#flock', 'https://github.com/ABustos2606/eureka#crinkle']
# Preserve selected project-owned identities when regenerating.
PEEPO += ['https://github.com/ABustos2606/midi-cv#mono', 'https://github.com/ABustos2606/midi-cv#poly', 'https://github.com/ABustos2606/midi-pc#pc']
EXAMPLES = ["eg-amp", "eg-fifths", "eg-metro", "eg-midigate", "eg-params", "eg-scope#Mono", "eg-scope#Stereo"]


def main():
    data = json.load(open(DATA))
    retired = {p["uri"] for p in json.load(open(RETIRED, encoding="utf-8"))["modules"]}
    sources = {}
    for plugin in data["poly_plugins"]:
        sources[plugin["uri"]] = sorted({s["repo"] for s in plugin["sources"]})
    keys = {}
    for mapping in data["beebo_mappings"]:
        keys.setdefault(mapping["uri"], []).append(mapping["key"])
    lines = ["# Plugins the catalogue may offer (P9.1). Generated by tools/catalogue-inventory.py",
             "# from docs/lv2-plugin-comparison-data.json; edit that script, not this file.",
             "# Listed is not supported: each entry's result is in docs/evidence/compatibility.json.", ""]
    groups = {}
    for uri in sorted(set(sources) | set(keys)):
        origin = ", ".join(sources.get(uri, [])) or "Beebo map only, no public Poly source"
        groups.setdefault(origin, []).append(uri)
    for origin in sorted(groups, key=lambda o: (o.startswith("Beebo"), o)):
        lines.append("# %s" % origin)
        for uri in groups[origin]:
            lines.append("%s%s" % (uri, ("  # Beebo: " + ", ".join(keys[uri])) if uri in keys else ""))
        lines.append("")
    lines.append("# Peepo's own plugins")
    lines += PEEPO
    lines.append("")
    lines.append("# GxPlugins: full collection (source pins in config/catalogue/gxplugins.json)")
    gx = json.load(open(GX, encoding="utf-8"))["plugins"]
    lines += [p["uri"] for p in gx if p["uri"] not in sources and p["uri"] not in keys]
    lines.append("")
    lines.append("# Development: MDA effects (also packaged for MODEP) and the LV2 examples the tests use")
    lines += ["http://drobilla.net/plugins/mda/" + name for name in MDA if "http://drobilla.net/plugins/mda/" + name not in keys]
    lines += ["http://lv2plug.in/plugins/" + name for name in EXAMPLES]
    lines += ["", "# Requested Patchstorage expansion: full Guitarix LV2 set and Dragonfly"]
    existing = {line.split("  #", 1)[0] for line in lines if line and not line.startswith("#")}
    expansion = json.load(open(PATCHSTORAGE, encoding="utf-8"))
    lines += [uri for uri in sorted({p["uri"] for e in expansion["entries"] for p in e["plugins"]}) if uri not in existing]
    # Reference maps remain historical evidence; retirement is our selection.
    lines = [line for line in lines if line.split("  #", 1)[0] not in retired]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    count = sum(1 for line in lines if line and not line.startswith("#"))
    print("%s: %d plugins (%d from Beebo and Poly sources)" % (OUT, count, len(set(sources) | set(keys))))


main()
